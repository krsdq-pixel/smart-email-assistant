import type { Account, EmailMessage } from './types';

export const protectedKeywords = [
  'invoice',
  'bank',
  'booking',
  'ticket',
  'starred',
  'reservation',
  'payment',
  'receipt',
  'flight',
  'hotel',
  'insurance',
];

export function shouldProtectEmail(email: EmailMessage): boolean {
  const haystack = `${email.subject} ${email.preview} ${email.sender}`.toLowerCase();
  const isCriticalCategory = ['invoices', 'banks', 'bookings', 'tickets', 'starred'].includes(email.category);
  return isCriticalCategory || protectedKeywords.some((keyword) => haystack.includes(keyword)) || email.isProtected;
}

